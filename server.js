/** 'YYYY-MM-DD' of a UTC millisecond time (no Date in the sandbox). */
function isoDay(ms) {
  var z = Math.floor(ms / 86400000) + 719468;
  var era = Math.floor(z / 146097);
  var doe = z - era * 146097;
  var yoe = Math.floor((doe - Math.floor(doe / 1460) + Math.floor(doe / 36524) - Math.floor(doe / 146096)) / 365);
  var y = yoe + era * 400;
  var doy = doe - (365 * yoe + Math.floor(yoe / 4) - Math.floor(yoe / 100));
  var mp = Math.floor((5 * doy + 2) / 153);
  var d = doy - Math.floor((153 * mp + 2) / 5) + 1;
  var m = mp < 10 ? mp + 3 : mp - 9;
  if (m <= 2) y += 1;
  return y + '-' + (m < 10 ? '0' : '') + m + '-' + (d < 10 ? '0' : '') + d;
}

/** Seats: the room's players by slot (at most four), then bot lanterns. */
function seatsFrom(ctx) {
  var roster = (ctx.room.roster || []).slice().sort(function (a, b) { return (a && a.slot || 0) - (b && b.slot || 0); });
  var seats = [];
  for (var i = 0; i < roster.length && seats.length < SEATS; i++) {
    var r = roster[i];
    if (!r || r.ai || typeof r.userId !== 'string' || !r.userId) continue;
    seats.push({ userId: r.userId, playerId: 'p' + (seats.length + 1), name: clampText(r.name, NAME_MAX) || 'Player ' + (seats.length + 1), ai: false, left: false });
  }
  var n = 1;
  while (seats.length < SEATS) { seats.push({ userId: null, playerId: 'lantern-' + n, name: 'lantern-' + n, ai: true, left: false }); n++; }
  return seats;
}

function startHall(ctx) {
  var day = isoDay(ctx.now);
  var daily = Content.dailyFor(day);
  var seed = (Math.floor(ctx.random * 4294967296) >>> 0) || 1;
  var seats = seatsFrom(ctx);
  var state = Rules.createGame({ seed: seed, pattern: daily.pattern, parCalls: daily.parCalls, playerIds: seats.map(function (s) { return s.playerId; }) });
  return {
    v: 1, mode: 'hall', seats: seats, state: state,
    stage: { id: 'hosted-' + day, day: day, pattern: daily.pattern, parCalls: daily.parCalls, theme: daily.theme, botSkill: BOT_SKILL, version: daily.version },
    cmd: 0, startedAt: ctx.now, nextCallAt: ctx.now + CALL_MS, exhaustedAt: null, over: null
  };
}

function seatOf(ss, userId) {
  for (var i = 0; i < ss.seats.length; i++) if (ss.seats[i].userId && ss.seats[i].userId === userId) return i;
  return -1;
}

/** Players who left the room keep their seat (and card) until the round ends; they just stop playing. */
function syncPresence(ss, ctx) {
  var presence = ctx.presence || {};
  var changed = false;
  for (var i = 0; i < ss.seats.length; i++) {
    var s = ss.seats[i];
    if (s.ai || s.left) continue;
    var p = presence[s.userId];
    if (p && p.left) { s.left = true; changed = true; }
  }
  return changed;
}

function everyoneLeft(ss) {
  for (var i = 0; i < ss.seats.length; i++) if (!ss.seats[i].ai && !ss.seats[i].left) return false;
  return true;
}

function apply(ss, cmd) {
  ss.cmd += 1;
  cmd.id = 's' + ss.cmd;
  cmd.tick = ss.state.tick;
  var r = Rules.applyCommand(ss.state, cmd);
  ss.state = r.state;
  return r;
}

/** One call, then the bot lanterns mark and claim (the browser build's HallHost.hostCall). */
function callNumber(ss) {
  var r = apply(ss, { type: 'call' });
  if (r.error) return false;
  var state = ss.state;
  var skill = typeof ss.stage.botSkill === 'number' ? ss.stage.botSkill : BOT_SKILL;
  for (var i = 0; i < state.players.length; i++) {
    var p = state.players[i];
    if (p.id.indexOf('lantern-') !== 0 || ss.state.phase !== 'active') continue;
    var notices = ((state.tick * 2654435761 + p.id.length * 97) % 1000) / 1000 < skill;
    if (notices) {
      var acts = Rules.legalActions(ss.state, p.id);
      for (var a = 0; a < acts.length; a++) {
        if (acts[a].type !== 'mark') continue;
        for (var c = 0; c < acts[a].cells.length && ss.state.phase === 'active'; c++) apply(ss, { type: 'mark', player: p.id, cell: acts[a].cells[c] });
      }
    }
    var me = null;
    for (var k = 0; k < ss.state.players.length; k++) if (ss.state.players[k].id === p.id) me = ss.state.players[k];
    if (me && ss.state.phase === 'active' && Rules.patternComplete(me.marks, ss.state.pattern)) apply(ss, { type: 'claim', player: p.id });
  }
  return true;
}

/** What every player sees: the state without the seed and the deck past the last call. */
function viewOf(ss) {
  var st = ss.state;
  var v = {};
  for (var k in st) if (own(st, k) && k !== 'seed' && k !== 'deck') v[k] = st[k];
  v.seed = 0;
  v.deck = st.deck.slice(0, st.callIndex + 1);
  return v;
}

function hallMessage(ss, seat) {
  return {
    type: 'hall',
    you: ss.seats[seat].playerId,
    seats: ss.seats.map(function (s) { return { playerId: s.playerId, name: s.name, ai: s.ai, left: s.left }; }),
    stage: ss.stage,
    nextCallIn: ss.over || ss.state.phase !== 'active' || ss.state.callIndex >= Rules.BALLS - 1 ? null : Math.max(0, ss.nextCallAt - ss.lastNow),
    state: viewOf(ss),
    over: ss.over
  };
}

function broadcastAll(ss) {
  var out = [];
  for (var i = 0; i < ss.seats.length; i++) {
    var s = ss.seats[i];
    if (!s.ai && !s.left) out.push({ to: [s.userId], data: hallMessage(ss, i) });
  }
  return out;
}

/** The round ended (a claim, the deck ran out, or everyone left): the result, recorded by the platform. */
function finish(ss, ctx, out, reason) {
  var st = ss.state;
  var seats = ss.seats.map(function (s) {
    var b = Rules.scoreBreakdown(st, s.playerId);
    return { userId: s.userId, playerId: s.playerId, name: s.name, ai: s.ai, left: s.left, won: st.winner === s.playerId, total: b.total };
  });
  var ranking = st.players.map(function (p) { return p.id; }).sort(function (a, b) { return Rules.compareResults(st, a, b); });
  ss.over = {
    winner: st.winner, reason: reason, calls: st.callIndex + 1, ranking: ranking,
    elapsedMs: Math.max(0, ctx.now - ss.startedAt), seats: seats, recorded: true
  };
  out.result = {
    kind: reason === 'abandoned' ? 'abandoned' : 'finished',
    winner: st.winner, reason: reason, calls: st.callIndex + 1, pattern: st.pattern,
    seats: seats
  };
}

function settle(ss, ctx, out, changed) {
  ss.lastNow = ctx.now;
  if (!ss.over) {
    if (ss.state.phase === 'ended') { finish(ss, ctx, out, ss.state.terminalReason || 'pattern-claimed'); changed = true; }
    else if (everyoneLeft(ss)) { finish(ss, ctx, out, 'abandoned'); changed = true; }
    else if (ss.exhaustedAt != null && ctx.now - ss.exhaustedAt >= EXHAUSTED_GRACE_MS) { finish(ss, ctx, out, 'deck-exhausted'); changed = true; }
  }
  out.ok = true;
  out.sessionState = ss;
  if (changed) out.broadcast = (out.broadcast || []).concat(broadcastAll(ss));
  return out;
}

/** The sender's mark or claim as a rules command for its own seat; else an error reason. */
function boundCommand(ss, seat, raw) {
  if (!raw || typeof raw !== 'object') return { reason: 'malformed-command' };
  var player = ss.seats[seat].playerId;
  if (raw.type === 'claim') return { cmd: { type: 'claim', player: player } };
  if (raw.type === 'mark') {
    var cell = raw.cell;
    if (typeof cell !== 'number' || Math.floor(cell) !== cell) return { reason: 'malformed-command' };
    if (cell < 0 || cell >= Rules.CELLS) return { reason: 'cell-out-of-bounds' };
    return { cmd: { type: 'mark', player: player, cell: cell } };
  }
  return { reason: 'unsupported-command' };
}

function hallMessageIn(ctx) {
  var ss = ctx.sessionState;
  var from = ctx.message.from;
  var data = ctx.message.data;
  if (!data || typeof data !== 'object') return { ok: false, error: 'malformed-command' };
  var seat = seatOf(ss, from);
  var out = {};
  syncPresence(ss, ctx);
  ss.lastNow = ctx.now;
  switch (data.type) {
    case 'sync':
      if (seat < 0) return { ok: false, error: 'unknown-player' };
      out.broadcast = [{ to: [from], data: hallMessage(ss, seat) }];
      return settle(ss, ctx, out, false);
    case 'act': {
      if (seat < 0 || ss.seats[seat].left) return { ok: false, error: 'unknown-player' };
      if (ss.over || ss.state.phase !== 'active') {
        out.broadcast = [{ to: [from], data: { type: 'rejected', reason: 'game-not-active' } }];
        return settle(ss, ctx, out, false);
      }
      var bound = boundCommand(ss, seat, data.cmd);
      if (!bound.cmd) {
        out.broadcast = [{ to: [from], data: { type: 'rejected', reason: bound.reason } }];
        return settle(ss, ctx, out, false);
      }
      var before = ss.state;
      var r = apply(ss, bound.cmd);
      if (r.error) out.broadcast = [{ to: [from], data: { type: 'rejected', reason: r.error, cell: bound.cmd.cell == null ? null : bound.cmd.cell } }];
      // A refused mark on an uncalled number or a false claim still counts (the rules' penalty).
      return settle(ss, ctx, out, ss.state !== before);
    }
    default:
      return { ok: false, error: 'unknown-command' };
  }
}

function hallTick(ctx) {
  var ss = ctx.sessionState;
  if (ss.over) return { ok: true };
  var changed = syncPresence(ss, ctx);
  if (!everyoneLeft(ss) && ss.state.phase === 'active' && ctx.now >= ss.nextCallAt) {
    if (ss.state.callIndex < Rules.BALLS - 1) {
      callNumber(ss);
      changed = true;
      ss.nextCallAt += CALL_MS;
      if (ss.nextCallAt <= ctx.now) ss.nextCallAt = ctx.now + CALL_MS; // never call twice to catch up
      if (ss.state.callIndex >= Rules.BALLS - 1 && ss.exhaustedAt == null) ss.exhaustedAt = ctx.now;
    }
  }
  if (!changed && ss.exhaustedAt == null && !everyoneLeft(ss)) { ss.lastNow = ctx.now; return { ok: true, sessionState: ss }; }
  return settle(ss, ctx, {}, changed);
}

globalThis.game = {
  // Four ticks a second: calls land within 250 ms of their 4 s cadence.
  tickRateHz: 4,

  createSession: function (ctx) {
    if (ctx.room) { var ss = startHall(ctx); return settle(ss, ctx, {}, true); }
    return { ok: true, sessionState: { mode: 'score', startedAt: ctx.now, summary: { status: 'active' } } };
  },

  onPlayerMessage: function (ctx) {
    var ss = ctx.sessionState;
    if (ss && ss.mode === 'hall') return hallMessageIn(ctx);
    return scoreMessage(ctx);
  },

  onTick: function (ctx) {
    var ss = ctx.sessionState;
    if (ss && ss.mode === 'hall') return hallTick(ctx);
    return { ok: true };
  }
};
