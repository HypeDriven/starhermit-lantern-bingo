// server=server.js), the one authority for everything recorded:
//
// 1. Hosted halls. A realtime room is the lobby (one team of four seats);
//    when the host starts it the platform binds a session to it and this
//    script referees the round (a room-bound session), as the browser
//    build's host tab (js/hallnet.js HallHost) and its dev server did: the
//    seats are the room's players, the empty ones bot lanterns; the pattern,
//    par and theme are the day's (content.js dailyFor on the platform's UTC
//    day), the deck is shuffled from the script's own seed; it calls a
//    number every 4 s, the bots mark and claim right after each call (the
//    same deterministic skill rule), and every mark or claim a player sends
//    is applied for the seat the platform says sent it, through the same
//    js/rules.js the solo game runs (written into the RULES block below by
//    tools/build-server.mjs). Each player gets the hall's view: the cards,
//    the marks and the numbers called so far, never the seed or the rest of
//    the deck. When a player claims a complete pattern, when the deck has
//    run out with no claim for 8 s, or when every player has left, it
//    returns the result — the winner and each seat's score — which closes
//    the room. No client reports a result. Hosted rounds post nothing to
//    the leaderboard (as before).
// 2. Score posting. A finished solo round (every mode but Learn) posts its
//    total on a practice session ({ type: 'result', scores }); the script
//    range-checks it against the high-score board and returns it in
//    `scores`, as score-script.js did (the user's decision: solo scores keep
