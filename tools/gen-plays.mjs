// Writes the play scripts in tests/native/ that play whole rounds through the
// real UI: the rules (js/rules.js) replay a seeded round as native/app.ts
// runs it — the auto caller every 5 s (the default call speed), the player
// marking each called number on the card as soon as it shows (a click on the
// cell by its screen-reader name), claiming the moment the pattern is
// complete, and each bot lantern reacting to a call after its skill-scaled
// delay (marking what it noticed, claiming a complete pattern) — so the
// script knows which numbers come, which cells to click and who wins.
//   node tools/gen-plays.mjs
import { writeFileSync } from 'node:fs';
import { createGame, applyCommand, legalActions, patternComplete, CENTER, GRID } from '../js/rules.js';
import { JOURNEY_STAGES, CHALLENGES, LESSONS } from '../js/content.js';

const ROOT = new URL('..', import.meta.url).pathname;

/** The round as app.ts plays it with a perfect, quick player 'you'. */
function simulate(stage, maxCalls = 75) {
  let state = createGame({ seed: stage.seed >>> 0, pattern: stage.pattern, parCalls: stage.parCalls, playerIds: ['you', ...Array.from({ length: stage.bots }, (_, i) => 'lantern-' + (i + 1))] });
  const apply = (cmd) => { const r = applyCommand(state, { ...cmd, tick: state.tick }); state = r.state; return r; };
  const calls = [];
  for (let c = 0; c < maxCalls && state.phase === 'active'; c++) {
    apply({ type: 'call' });
    const v = state.currentCall;
    const atCall = state.tick;
    const step = { value: v, marks: [], claim: false };
    const mark = legalActions(state, 'you').find((a) => a.type === 'mark');
    if (mark) for (const cell of mark.cells) { apply({ type: 'mark', player: 'you', cell }); step.marks.push({ cell, n: state.players[0].card[cell] }); }
    if (patternComplete(state.players[0].marks, state.pattern)) { apply({ type: 'claim', player: 'you' }); step.claim = true; }
    calls.push(step);
    if (state.phase !== 'active') break;
    // The bots, in the order their timers fire (delay from the tick at the call).
    const skill = stage.botSkill || 0.6;
    const bots = state.players.filter((p) => p.id.startsWith('lantern-'))
      .map((p, i) => ({ id: p.id, i, delay: 600 + (1 - skill) * 4000 + ((atCall * 7919 + p.id.length * 131) % 700) }))
      .sort((a, b) => a.delay - b.delay || a.i - b.i);
    for (const b of bots) {
      if (state.phase !== 'active') break;
      const m = legalActions(state, b.id).find((a) => a.type === 'mark');
      const notices = ((state.tick * 2654435761 + b.id.length * 97) % 1000) / 1000 < skill;
      if (m && notices) for (const cell of m.cells) { if (state.phase !== 'active') break; apply({ type: 'mark', player: b.id, cell }); }
      const me = state.players.find((p) => p.id === b.id);
      if (state.phase === 'active' && patternComplete(me.marks, state.pattern)) apply({ type: 'claim', player: b.id });
    }
    if (state.phase !== 'active') break;
  }
  return { calls, winner: state.winner, state };
}
const cellName = (cell, n) => `row ${Math.floor(cell / GRID) + 1} column ${(cell % GRID) + 1}, number ${n}, callable`;

/** Steps that play the simulated calls (waiting for each call, clicking its marks, claiming). */
function playSteps(sim) {
  const out = [];
  for (const c of sim.calls) {
    out.push(`until 600 =Called ${c.value}`, 'frames 3');
    for (const m of c.marks) out.push(`click =${cellName(m.cell, m.n)}`, 'frames 3');
    if (c.claim) out.push('click =Claim', 'frames 3');
  }
  return out;
}

function journeyStage1() {
  const stage = JOURNEY_STAGES[0];
  const sim = simulate(stage);
  if (sim.winner !== 'you') throw new Error(`journey stage 1: ${sim.winner} wins`);
  return [
    `# Journey stage 1 (${stage.pattern}, one bot) played to a win through the card (generated by tools/gen-plays.mjs:`,
    `# ${sim.calls.length} calls, the player marks every called number and claims the line).`,
    'until 300 Lantern Bingo', 'frames 60',
    'click =Journey', 'until 60 Stage 1', 'frames 10', 'save journey',
    'click Stage 1 — Any Line', 'until 60 Mode Setup', 'frames 10', 'expect Ranked result.',
    'click =Start', 'until 300 Round active', 'frames 5',
    ...playSteps(sim),
    'until 240 Bingo! You lit the hall.', 'frames 30', 'expect Total', 'expect Ranking', 'save results',
    'click =Next stage', 'until 60 Mode Setup', 'expect Stage 2', 'frames 5',
  ].join('\n') + '\n';
}

function challenge(idx, name) {
  const stage = CHALLENGES[idx];
  const sim = simulate(stage);
  return [
    `# Challenge "${stage.title}" (${stage.pattern}, ${stage.bots} bots) from the Challenge picker; the player marks every`,
    `# call; ${sim.winner === 'you' ? 'the player claims first' : sim.winner + ' claims first'} after ${sim.calls.length} calls (generated by tools/gen-plays.mjs). Hint, a`,
    '# false-claim-free pause, Settings from the pause dialog and back.',
    'until 300 Lantern Bingo', 'frames 60',
    'click =Challenge', 'until 60 Constrained ranked goals', 'frames 10', 'save challenge-picker',
    `click =${stage.title}`, 'until 60 Mode Setup', 'frames 10', `expect ${stage.constraint}`,
    'click =Start', 'until 300 Round active', 'frames 5',
    ...playSteps({ calls: sim.calls.slice(0, 2) }),
    'key KeyH 1', 'frames 5', 'key KeyP 1', 'until 60 Take your time', 'frames 10', 'save pause',
    'click =Settings', 'until 60 Accessibility', 'frames 10', 'click =Done', 'until 60 Take your time', 'frames 10',
    'click =Resume', 'frames 10',
    ...playSteps({ calls: sim.calls.slice(2) }),
    `until 240 ${sim.winner === 'you' ? 'Bingo! You lit the hall.' : `${sim.winner} claimed first.`}`, 'frames 20', 'save results',
    'click =Continue', 'until 60 =Play', 'frames 5',
  ].join('\n') + '\n';
  void name;
}

function lesson(idx) {
  const l = LESSONS[idx];
  const sim = simulate({ seed: l.seed, pattern: l.pattern, bots: 0, botSkill: 0, parCalls: 0 });
  return [
    `# Learn: "${l.title}" — each step waits for the player's action; played to the claim (generated by tools/gen-plays.mjs).`,
    'until 300 Lantern Bingo', 'frames 60',
    'click =Learn', 'until 60 Lines and Claims', 'frames 10',
    `click ${l.title}`, 'until 300 Lesson 1/', 'frames 5',
    ...playSteps(sim),
    'until 240 Bingo! You lit the hall.', 'frames 20', 'save lesson-results',
    'click =Continue', 'until 60 =Play', 'frames 5',
    'click =Learn', 'until 60 ✓', 'frames 5',
  ].join('\n') + '\n';
}

writeFileSync(ROOT + 'tests/native/journey-stage1.play', journeyStage1());
writeFileSync(ROOT + 'tests/native/challenge-speed.play', challenge(0));
writeFileSync(ROOT + 'tests/native/learn-lines.play', lesson(1));
console.log('wrote tests/native/journey-stage1.play, challenge-speed.play, learn-lines.play');
export { simulate };
